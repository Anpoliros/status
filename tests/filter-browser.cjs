/** Browser regression checks for cluster drag gestures, shared order and scoped filters. */
const {chromium}=require(process.env.STATUS_PLAYWRIGHT_PATH || 'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true, ...(process.env.STATUS_CHROMIUM_PATH ? { executablePath: process.env.STATUS_CHROMIUM_PATH } : {})});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const servers=Array.from({length:5},(_,i)=>({id:i+1,resource_id:`host-${i}`,name:i===4?'AAA bastion':`Host ${i}`,cluster:i===4?'bastion':'compute',status:'healthy',cpu_usage:10,memory_usage:20,disk_usage:30}));
 await page.route('**/api/session',r=>r.fulfill({json:{full_access:true,refresh:{presets:[10,20,60],minimum_seconds:10}}}));
 await page.route('**/status',r=>r.fulfill({json:{servers,services:[],collected_at:{}}}));
 await page.route('**/history/**',r=>r.fulfill({json:{items:servers.map(s=>({...s,buckets:[]}))}}));
 await page.route('**/api/control',r=>r.fulfill({json:{}}));
 await page.goto(process.env.STATUS_TEST_URL || 'http://127.0.0.1:18081');
 await page.locator('.machineCard').first().waitFor();
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByRole('tab',{name:'Display',exact:true}).click();
 await page.locator('.settingRow').filter({hasText:'Sort by'}).locator('select').selectOption('name');
 assert.equal(await page.locator('.clusterHeader h2').first().innerText(),'compute','Name sorting must not change configured cluster order');
 await page.getByRole('tab',{name:'Filter',exact:true}).click();
 assert.equal(await page.locator('.filterClusterTitle strong').first().innerText(),'compute');
 const compute=page.locator('.filterClusterTitle').filter({hasText:'compute'});
 await compute.click();assert.equal(await page.locator('.machineFilter').count(),1);
 await compute.click();assert.equal(await page.locator('.machineFilter').count(),5);
 // Hold the cluster title before moving it above compute.
 const bastion=page.locator('.filterClusterTitle').filter({hasText:'bastion'});
 const b=await bastion.boundingBox(),c=await compute.boundingBox();
 await page.mouse.move(b.x+60,b.y+15);await page.mouse.down();await page.waitForTimeout(400);await page.mouse.move(c.x+60,c.y+15);
 await page.waitForTimeout(160);
 assert.equal(await page.locator('.clusterHeader h2').first().innerText(),'compute', 'Do not reorder until drop');
 assert.equal(await page.locator('.dropBefore').count(),1);
 await page.mouse.up();
 assert.equal(await page.locator('.clusterHeader h2').first().innerText(),'bastion');
 // An immediate handle drag and keyboard movement must produce the same order.
 const handle=page.locator('[data-filter-cluster="compute"] [data-drag-handle]');
 const h=await handle.boundingBox(), first=await bastion.boundingBox();
 await page.mouse.move(h.x+h.width/2,h.y+h.height/2);await page.mouse.down();
 await page.mouse.move(first.x+50,first.y+5);await page.mouse.up();
 assert.equal(await page.locator('.clusterHeader h2').first().innerText(),'compute');
 await bastion.focus();await page.keyboard.press('Alt+ArrowUp');
 assert.equal(await page.locator('.clusterHeader h2').first().innerText(),'bastion');
 await page.getByRole('tab',{name:'Display',exact:true}).click();
 await page.locator('.settingRow').filter({hasText:'Sort by'}).locator('select').selectOption('name');
 assert.equal(await page.locator('.clusterHeader h2').first().innerText(),'bastion');
 await page.getByRole('tab',{name:'Filter',exact:true}).click();
 await page.getByLabel('Show bastion',{exact:true}).uncheck();
 assert.equal(await page.locator('.machineCard').count(),4);
 await page.getByRole('button',{name:'History',exact:true}).click();
 await page.locator('.historyRow').first().waitFor();assert.equal(await page.locator('.historyRow').count(),5);
 assert.equal(await page.locator('.historyIdentity strong').first().innerText(),'AAA bastion', 'History shares the cluster order');
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByLabel('Show compute',{exact:true}).uncheck();assert.equal(await page.locator('.historyRow').count(),1);
 await page.getByRole('button',{name:'Status',exact:true}).click();assert.equal(await page.locator('.machineCard').count(),4);
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByRole('button',{name:'Show all',exact:true}).click();
 await page.getByRole('tab',{name:'Display',exact:true}).click();
 await page.locator('.settingRow').filter({hasText:'Layout'}).locator('select').selectOption('grid');
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 const widths=await page.locator('.machineCard').evaluateAll(cards=>cards.map(c=>c.getBoundingClientRect().width));assert.ok(Math.max(...widths)-Math.min(...widths)<1,JSON.stringify(widths));
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.reload();await page.locator('.machineCard').first().waitFor();
 await page.getByRole('button',{name:'History',exact:true}).click();await page.locator('.historyRow').first().waitFor();assert.equal(await page.locator('.historyRow').count(),1);
 // A stationary pointer near the menu edge must scroll long cluster lists.
 const many = Array.from({length:22},(_,i)=>({...servers[0],id:100+i,resource_id:`many-${i}`,name:`Many ${i}`,cluster:`Cluster ${i}`}));
 await page.route('**/status',r=>r.fulfill({json:{servers:many,services:[],collected_at:{}}}));
 await page.setViewportSize({width:1440,height:1000});
 await page.reload();await page.locator('.machineCard').first().waitFor();
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 const scrollPanel=page.locator('.settingsContent');
 const scrollBox=await scrollPanel.boundingBox();
 const firstHandle=await page.locator('[data-drag-handle]').first().boundingBox();
 await page.mouse.move(firstHandle.x+5,firstHandle.y+5);await page.mouse.down();
 await page.mouse.move(scrollBox.x+50,scrollBox.y+scrollBox.height-5);
 await page.waitForTimeout(400);
 assert.ok(await scrollPanel.evaluate(element=>element.scrollTop)>0,'Drag scrolls the filter menu');
 await page.mouse.up();
 assert.deepEqual(errors,[]);console.log('PASS: collapse, held-pointer reorder, independent persistent filters, equal grid widths, mobile overflow, no browser errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
